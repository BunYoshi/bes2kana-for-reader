 export function convertSymbols(text: string): string {
    const result = text
    .replace(/☆☆☆/g, 'ハナジルシ…')
    .replace(/☆☆/g, 'コメジルシ…')
    .replace(/☆/g, 'ホシジルシ…')
    .replace(/\/\/＿/g, '／')
    .replace(/\/＿/g, '／')
    // .replace(/⠪⠒⠒⠕/g, '⇔')
    // .replace(/⠒⠒⠕/g, '→')
    // .replace(/⠪⠒⠒/g, '←')
    // .replace(/⠂⠂⠂/g, '……')
    // .replace(shijifu3Regex, '【$1】')
    // .replace(shijifu2Regex, '“$1”')
    // .replace(shijifu1Regex, '‘$1’')
    .replace(/＜/g, '「')
    .replace(/＞/g, '」')
    // .replace(/⠰⠤/g, '『')
    // .replace(/⠤⠆/g, '』')
    // .replace(/⠐⠶(.*?)⠶⠂/gu, '｛$1｝')
    // .replace(/⠐⠶(.*?)⠶⠂/gu, '｛$1｝')
    // .replace(/⠰⠶/g, '((')
    // .replace(/⠶⠆/g, '))')
    // .replace(/⠠⠄/g, '=')
    // .replace(/⠠⠤/g, '…')
    // .replace(/⠐⠂/g, '：')
    .replace(/※/g, 'チュー')
    .replace(/○/g, 'マル')
    .replace(/△/g, 'サンカク')
    .replace(/□/g, 'シカク')
    .replace(/×/g, 'バツ')
    .replace(/◇/g, 'チョメ')
    // .replace(/⠰([0-9]+)⠆/gu, '※$1') // 数字入り文中注記符後に「…」を挿入
    // .replace(/⠰/g, '、')
    .replace(/～/g, 'カラ')
    // .replace(/⠤/g, '_')
    // .replace(/⠶/g, '│')
    // .replace(createRegex('⠲'), '。')
    // .replace(createRegex('⠠⠢'), '☆☆☆')
    // .replace(createRegex('⠢'), '？')
    // .replace(/⠐\u2800/g, '・\u2800')
    // .replace(createRegex('⠖'), '！')
    .replace(/(?<=.)(?<!　|。|？|@|！|／)　{2}(?!　|／)/gu, '、') // ２マス分のスペースは「、」に変換
    return result
 }